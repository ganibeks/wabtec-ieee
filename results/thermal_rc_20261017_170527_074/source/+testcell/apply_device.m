function apply_device(q,p,T_C)
% Full I-V and charge model, without thermal feedback during electrical checks.
set_param(q,'model_type','ee.enum.igbt.parameterization.equation', ...
 'Ices',num2str(p.leakageCalibration_A,17),'Ices_unit','A', ...
 'Vces',num2str(p.leakageCalibrationVoltage_V),'Vth',num2str(p.Vth_V), ...
 'Vce_sat',num2str(p.VceCalibration_V),'Ice_sat',num2str(p.IcCalibration_A), ...
 'Vge_sat',num2str(p.gateOn_V),'Tmeas',num2str(p.Tcal_C),'Tmeas_unit','degC', ...
 'C_ies',num2str(p.Cies_F,17),'C_ies_unit','F', ...
 'C_res',num2str(p.Cres_F,17),'C_res_unit','F', ...
 'C_oes',num2str(p.Coes_F,17),'C_oes_unit','F', ...
 'TF',num2str(p.transit_s,17),'TF_unit','s', ...
 'RC',num2str(p.Rc_Ohm),'RE',num2str(p.Re_Ohm),'RG',num2str(p.RgInternal_Ohm), ...
 'Tmeas2',num2str(p.Tsecond_C),'Tmeas2_unit','degC', ...
 'Vce_sat_T2',num2str(p.VceSecond_V), ...
 'Ices_T2',num2str(p.leakageSecond_A,17),'Ices_T2_unit','A', ...
 'Tdevice',num2str(T_C),'Tdevice_unit','degC');
% Temperature enum selected from installed library by inspect_detailed.m.
set_param(q,'T_param','ee.enum.igbt.temperatureParameterization.IcesVce');
end

